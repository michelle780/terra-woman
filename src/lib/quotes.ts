/** Deterministic quote of the day — same for a given YYYY-MM-DD. */
export function quoteOfTheDay(dateKey: string): DailyQuote {
  const days = Math.floor(new Date(`${dateKey}T00:00:00Z`).getTime() / 86_400_000);
  const index = ((days % QUOTES.length) + QUOTES.length) % QUOTES.length;
  return QUOTES[index] ?? QUOTES[0]!;
}
